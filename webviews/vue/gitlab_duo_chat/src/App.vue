<script>
export default {
  name: 'GitLabDuoChat',
  mounted() {
    const vscode = acquireVsCodeApi();
    const chatRequestArea = document.getElementById('chatPromptInput');

    const submitPrompt = event => {
      event.preventDefault();
      vscode.postMessage({
        eventType: 'newPrompt',
        record: {
          text: chatRequestArea.value,
        },
      });
      chatRequestArea.value = null;
    };

    document.getElementById('submitPrompt').onclick = submitPrompt;
    chatRequestArea.addEventListener('keypress', event => {
      if (event.key === 'Enter' && event.shiftKey) {
        submitPrompt(event);
      }
    });

    const buildMessageBlock = message => {
      const messageBlock = document.createElement('div');
      messageBlock.id = `message-${message.record.id}`;
      messageBlock.classList.add('message');

      if (message.record.author === 'user') {
        messageBlock.classList.add('prompt');
      } else {
        messageBlock.classList.add('response');
      }

      messageBlock.append(message.record.text);

      return messageBlock;
    };

    const newMessage = message => {
      const chatHistory = document.getElementById('chatHistory');
      const messageBlock = buildMessageBlock(message);
      chatHistory.append(messageBlock);
    };

    const updateMessage = message => {
      document.getElementById(`message-${message.record.id}`).innerHTML = message.record.text;
    };

    const handleExtensionMessageEvent = event => {
      const message = event.data;
      console.log('received', message);

      if (message.eventType === 'focus') {
        document.getElementById('chatPromptInput').focus();
        return;
      }

      if (message.eventType === 'updateRecord') {
        updateMessage(message);
        return;
      }

      newMessage(message);
    };

    window.addEventListener('message', handleExtensionMessageEvent);

    vscode.postMessage({ command: 'appReady' }); // Must be last line
  },
};
</script>
<template>
  <div id="app">
    <div id="chatHeader">Responses generated by AI.</div>
    <div id="chatHistory"></div>
    <div id="chatInputBlock">
      <hr />
      <textarea
        id="chatPromptInput"
        name="chatPromptInput"
        rows="1"
        placeholder="Ask a question"
      ></textarea>
      <button id="submitPrompt">Send</button>
    </div>
  </div>
</template>
