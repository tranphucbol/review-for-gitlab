<script>
import AiGenieChatMessage from './components/AiGenieChatMessage.vue';

const vscode = acquireVsCodeApi();

export default {
  name: 'GitLabDuoChat',
  components: {
    AiGenieChatMessage,
  },
  data() {
    return {
      chatMessages: [],
      promptDraft: null,
    };
  },
  created() {
    window.vsCodeApi = vscode;
    window.addEventListener('message', this.handleExtensionMessageEvent);
    window.vsCodeApi.postMessage({ command: 'appReady' });
  },
  onBeforeDestroy() {
    window.removeEventListener('message', this.handleExtensionMessageEvent);
  },
  methods: {
    handleExtensionMessageEvent(event) {
      const message = event.data;
      console.log('received', message);

      switch (message.eventType) {
        case 'focus': {
          this.focusInput();
          break;
        }
        case 'newRecord': {
          this.newRecord(message.record);
          break;
        }
        case 'updateRecord': {
          this.updateRecord(message.record);
          break;
        }
        default:
          console.log('Chat view received unexpected message type.');
          break;
      }
    },
    newRecord(record) {
      this.chatMessages.push(record);
    },
    updateRecord(record) {
      const index = this.chatMessages.findIndex(r => r.id === record.id);

      this.chatMessages[index] = record;
    },
    // form related stuff.
    submitPrompt() {
      window.vsCodeApi.postMessage({
        eventType: 'newPrompt',
        record: {
          content: this.promptDraft,
        },
      });
      this.promptDraft = null;
    },
    handleKeyPress(event) {
      if (event.key === 'Enter' && event.shiftKey) {
        this.submitPrompt();
      }
    },
    focusInput() {
      this.$refs.promptTextarea.focus();
    },
  },
};
</script>
<template>
  <div id="app">
    <div class="header"><p>Responses generated by AI.</p></div>
    <div id="chatHistory">
      <ai-genie-chat-message v-for="message in chatMessages" :key="message.id" :message="message" />
    </div>
    <div id="promptForm">
      <hr />
      <textarea
        rows="1"
        placeholder="Ask a question"
        ref="promptTextarea"
        v-model="promptDraft"
        @keypress="handleKeyPress"
      ></textarea>
      <button id="submitPrompt" @click.prevent="submitPrompt">Send</button>
    </div>
    <div class="footer">
      <p>
        May provide inappropriate responses not representative of GitLab's views. Do not input
        personal data.
      </p>
    </div>
  </div>
</template>
